def load_navigator(checkpoint_path: Optional[str] = None) -> AddressNavigator:
    """Load AddressNavigator from bloom_checkpoint.pt (default: current directory)."""
    if checkpoint_path is None:
        checkpoint_path = str(Path(__file__).parent / 'bloom_checkpoint.pt')
    return AddressNavigator(checkpoint_path)


def compare_to_neural(
    checkpoint_path: str,
    model_path: str,
    n_tokens: int = 89,
    n_samples: int = 5,
) -> None:
    """Generate n_samples with navigator and n_samples with neural model, compare."""
    nav = load_navigator(checkpoint_path)

    # Try loading neural model
    try:
        import sys
        sys.path.insert(0, str(Path(checkpoint_path).parent))
        from substrate_tokenizer import SubstrateTokenizer
        from train_substrate_attention import FibRecLMSubsim
        import io, contextlib

        mck = torch.load(model_path, map_location='cpu', weights_only=False)
        vocab = mck['vocab']
        seq_len = mck.get('seq_len', 34)
        d_model = mck.get('d_model', 64)

        with open(str(Path(checkpoint_path).parent / 'tinyshakespeare.txt')) as f:
            corpus = f.read()
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            tok = SubstrateTokenizer(corpus)

        # Infer K from qkv_seed_0 shape: [K*K, 4] so K = sqrt(shape[0])
        qkv_seed_shape = mck['model_state']['qkv_seed_0'].shape
        K_inferred = int(qkv_seed_shape[0] ** 0.5)
        # Infer seq_len from pe shape if available
        seq_len_inferred = mck['model_state'].get('pe', torch.zeros(seq_len, 1)).shape[0]
        if seq_len_inferred != seq_len:
            seq_len = seq_len_inferred
        neural_model = FibRecLMSubsim(
            vocab_size=tok.vocab_size,
            d_model=d_model,
            n_blocks=4,
            seq_len=seq_len,
            K=K_inferred,
            K_sig=K_inferred,
        )
        neural_model.load_state_dict(mck['model_state'], strict=False)
        neural_model.eval()
        print("[compare] Neural model loaded successfully.", flush=True)
        has_neural = True
    except Exception as e:
        print(f"[compare] Could not load neural model: {e}", flush=True)
        has_neural = False

    def _rwf(text: str, registry: Dict) -> float:
        words = re.findall(r'[a-zA-Z]+', text.lower())
        long_words = [w for w in words if len(w) >= 3]
        if not long_words:
            return 0.0
        return sum(1 for w in long_words if w in registry) / len(long_words)

    print("\n" + "="*60)
    print("STAGE 3 NAVIGATOR  vs  NEURAL MODEL  (side-by-side)")
    print("="*60)

    nav_rwf_list = []
    neural_rwf_list = []

    for i in range(n_samples):
        nav_text, _ = nav.navigate_generate(n_tokens, temperature=0.8)
        nav_rwf = _rwf(nav_text, nav.word_registry)
        nav_rwf_list.append(nav_rwf)

        if has_neural:
            # Neural sampling
            with open(str(Path(checkpoint_path).parent / 'tinyshakespeare.txt')) as f:
                seed_text = f.read()[:seq_len]
            seed_ids = [tok.token_to_id.get(c, 0) for c in seed_text]
            x = torch.tensor(seed_ids[-seq_len:], dtype=torch.long).unsqueeze(0)
            generated = []
            with torch.no_grad():
                for _ in range(n_tokens):
                    logits = neural_model(x)[:, -1, :]
                    probs = torch.softmax(logits / 0.8, dim=-1)
                    next_id = int(torch.multinomial(probs, 1).item())
                    generated.append(next_id)
                    next_tok = torch.tensor([[next_id]], dtype=torch.long)
                    x = torch.cat([x[:, 1:], next_tok], dim=1)
            neural_text = ''.join(tok.vocab[t] for t in generated)
            neural_rwf = _rwf(neural_text, nav.word_registry)
            neural_rwf_list.append(neural_rwf)

        print(f"\n--- Sample {i+1} ---")
        print(f"  Navigator: {nav_text!r}")
        print(f"  real_word_fraction: {nav_rwf:.3f}")
        if has_neural:
            print(f"  Neural:    {neural_text!r}")
            print(f"  real_word_fraction: {neural_rwf:.3f}")

    print("\n" + "-"*60)
    nav_mean = sum(nav_rwf_list) / len(nav_rwf_list)
    print(f"  Navigator avg real_word_fraction: {nav_mean:.3f}")
    if has_neural and neural_rwf_list:
        neural_mean = sum(neural_rwf_list) / len(neural_rwf_list)
        print(f"  Neural    avg real_word_fraction: {neural_mean:.3f}")
        delta = nav_mean - neural_mean
        print(f"  Delta (nav - neural):             {delta:+.3f}")
    print("="*60)


