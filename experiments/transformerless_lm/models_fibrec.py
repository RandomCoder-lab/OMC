# Golden ratio — the fixed-point attractor of the Fibonacci recurrence.
# All Fibonacci sequences converge to ratio phi between consecutive terms.
PHI = (1.0 + math.sqrt(5.0)) / 2.0          # ≈ 1.61803
PHI_INV = 1.0 / PHI                           # ≈ 0.61803  (= phi - 1)
PHI_INV2 = PHI_INV * PHI_INV                  # ≈ 0.38197  (= 1 - phi^{-1})
# Natural scale for homeostatic OmniWeight: crossover at delta ~ phi^{-2}.
# delta < phi^{-2}: organism healthy, homeostasis fully active.
# delta > phi^{-2}: organism stressed, homeostasis yields to gradient.
_LOG_PHI = math.log(PHI)                      # used in exp-form of phi^x


def _smooth_norm(v: torch.Tensor, eps: float = 1e-8) -> torch.Tensor:
    """Smooth L2 norm: sqrt(v·v + eps²).

    Unlike torch.norm, this has a well-defined gradient at v=0 because
    the inner eps² lifts the cusp. Required for differentiable delta_n.
    """
    return (v.pow(2).sum() + eps * eps).sqrt()


def _phi_delta(s_n: torch.Tensor, s_p1: torch.Tensor,
               eps: float = 1e-8) -> torch.Tensor:
    """Compute the golden-ratio deviation scalar delta_n.

    delta_n = ||s_n - phi * s_{n-1}|| / (||s_{n-1}|| + eps)

    This is zero when s_n / s_{n-1} = phi everywhere (perfect Fibonacci
    sequence). Non-zero means the organism has drifted from its attractor.

    Args:
        s_n:  current seed  [K²*4] or any shape
        s_p1: previous seed [same shape]
        eps:  denominator stabiliser (prevents div-by-zero at init)
    """
    numerator = _smooth_norm(s_n - PHI * s_p1, eps)
    denominator = _smooth_norm(s_p1, eps) + eps
    return numerator / denominator


def _homeostatic_H(s_p1: torch.Tensor, s_p2: torch.Tensor,
                   delta_prev: torch.Tensor) -> torch.Tensor:
    """Compute the homeostatic restoring vector H_n.

    H_n = -phi^{-1} * delta_{n-1} * (s_{n-1} - phi^{-1} * s_{n-2})

    Derivation of each factor:

    1.  The direction term  (s_{n-1} - phi^{-1} * s_{n-2}):
        If s_{n-1} = phi * s_{n-2} (at the golden attractor), this
        equals  (phi - phi^{-1}) * s_{n-2} = 1 * s_{n-2}  (since
        phi - phi^{-1} = 1 by the identity phi^{-1} = phi - 1).
        So the direction term measures "how much of s_{n-2} is
        carried in s_{n-1} beyond what phi^{-1} would predict."
        When the organism is healthy, it points along s_{n-2}.
        When the organism is sick, it points in the direction of
        the deviation. Negating this vector pulls s_n BACK toward
        the attractor.

    2.  The scalar factor  delta_{n-1}:
        Scales the correction proportionally to how sick the organism
        currently is. Zero correction at zero deviation (neutral at
        health), growing with deviation. This ensures the restoring
        force is zero exactly at the fixed point.

    3.  The prefactor  -phi^{-1}:
        Sets the equilibrium gain. If we expand seed_n at the fixed
        point (delta -> 0, s_n = phi * s_{n-1}) the H_n term vanishes
        (because delta = 0). Near the fixed point, the derivative of
        H_n with respect to the deviation is -phi^{-1} * direction,
        which is the correct linear-restoring rate for the golden
        ratio. The factor phi^{-1} is the reciprocal of the attractor
        ratio — it is the "inverse metabolism rate."

    Args:
        s_p1:       s_{n-1}  [any shape]
        s_p2:       s_{n-2}  [same shape]
        delta_prev: delta_{n-1} (scalar tensor)
    """
    direction = s_p1 - PHI_INV * s_p2    # deviation from phi-ratio at step n-1
    return -PHI_INV * delta_prev * direction


def _homeostatic_strength(delta_prev: torch.Tensor) -> torch.Tensor:
    """Compute the OmniWeight-shaped restoring force strength.

    H_strength = phi^{-delta_{n-1} / phi^{-2}}
               = exp(-delta_{n-1} * log(phi) / phi^{-2})

    This is the OmniWeight formula  w = phi^{-|x - target| / scale}
    applied with x = delta_{n-1}, target = 0 (health), scale = phi^{-2}.

    WHY phi^{-2} as the scale?
        phi^{-2} ≈ 0.382 is the second negative power of phi. It is
        also the reciprocal of the first Fibonacci-ratio overshoot:
        F(n+1)/F(n) - phi < phi^{-2} for all n >= 1. So phi^{-2} is
        the "quantisation step" of the golden ratio — the smallest
        meaningful deviation unit in the Fibonacci metric.

    WHY does strength DECREASE when delta is large? (the paradox)
        Naive biology: sicker organism needs stronger medicine.
        But this ignores feedback dynamics. When delta is very large:
          - The seeds have already diverged catastrophically.
          - A large restoring force causes OVERCORRECTION: the correction
            blasts the seed past the target and into the opposite
            deviation. This is a cytokine storm — the immune overreaction
            kills the patient.
          - Moreover, a large H_n gradient dwarfs the task-loss gradient,
            so A and B stop learning the task entirely.
        Correct biology: when severely ill, the organism RETREATS homeostasis
        and lets slower regulatory mechanisms (gradient descent on A,B)
        do the heavy lifting. The immune system quiets; the organism
        recovers gradually, not explosively.
        At delta >> phi^{-2}:
          - H_strength -> 0 (homeostasis off)
          - Recurrence reduces to: seed_n = A * s_{n-1} + B * s_{n-2}
          - Gradient pressure on A,B is undiluted — they learn fast
          - Once A,B restore approximate phi-ratio, delta drops,
            homeostasis re-engages at full strength.

    Crossover analysis:
        delta = 0:         strength = 1.0   (healthy: full homeostasis)
        delta = phi^{-2}:  strength = phi^{-1} ≈ 0.618  (stressed: half-power)
        delta = 1.0:       strength ≈ 0.284  (sick: gentle pull)
        delta >> 1:        strength -> 0     (critical: homeostasis yields)

    Args:
        delta_prev: delta_{n-1} (scalar tensor, >= 0)
    """
    # phi^{-delta / phi^{-2}} = exp(-delta * log(phi) / phi^{-2})
    exponent = -delta_prev * (_LOG_PHI / PHI_INV2)
    return torch.exp(exponent)


def make_fib_basis(in_features: int, out_features: int, K: int,
                    device=None) -> dict:
    """Precompute cos/sin basis tables for FibGen forward."""
    i_idx = torch.arange(out_features, device=device).float()
    j_idx = torch.arange(in_features, device=device).float()
    freqs = torch.tensor(FIBONACCI[:K], device=device, dtype=torch.float)
    a_i = 2 * math.pi * i_idx.unsqueeze(1) * freqs.unsqueeze(0) / max(out_features, 1)
    a_j = 2 * math.pi * j_idx.unsqueeze(1) * freqs.unsqueeze(0) / max(in_features, 1)
    return {
        "cos_i": torch.cos(a_i), "sin_i": torch.sin(a_i),
        "cos_j": torch.cos(a_j), "sin_j": torch.sin(a_j),
    }


def stateless_fibgen_forward(x: torch.Tensor, seed: torch.Tensor,
                              basis: dict, K: int, mode: str = "cross",
                              K_active: int = None) -> torch.Tensor:
    """y = W(seed) · x without storing W. seed shape: [n_components, 4].

    K_active (optional): if set and < K, use only the FIRST K_active Fibonacci
    frequencies per axis (lowest, kept-first — matching FibGenLinear's lazy-K
    semantics). This makes the K-shrink schedule actually affect the forward
    pass for models that call this stateless fn (FibRecLMSubsim). Default
    None → full K → bit-identical to the original behavior.
    """
    if mode != "cross":
        raise NotImplementedError("only cross mode supported")
    sc = seed.view(K, K, 4)
    if K_active is not None and 0 < K_active < K:
        ka = K_active
        sc    = sc[:ka, :ka]                          # [ka, ka, 4]
        cos_j = basis["cos_j"][:, :ka]                # [in, ka]
        sin_j = basis["sin_j"][:, :ka]
        cos_i = basis["cos_i"][:, :ka]                # [out, ka]
        sin_i = basis["sin_i"][:, :ka]
    else:
        cos_j, sin_j = basis["cos_j"], basis["sin_j"]
        cos_i, sin_i = basis["cos_i"], basis["sin_i"]
    a, b, c, d = sc[..., 0], sc[..., 1], sc[..., 2], sc[..., 3]
    x_cos = x @ cos_j                                 # [B, T, ka|K]
    x_sin = x @ sin_j
    y_cos = x_cos @ a.t() + x_sin @ c.t()
    y_sin = x_cos @ b.t() + x_sin @ d.t()
    y = y_cos @ cos_i.t() + y_sin @ sin_i.t()
    return y


class FibRecLM(nn.Module):
    """LM with inter-layer Fibonacci recurrence on FibGen seeds.

    Architecture:
      - Embedding + CRT-Fibonacci PE
      - Block 0: uses base_seed_0
      - Block 1: uses base_seed_1
      - Block n>=2: uses seed_n = A · seed_{n-1} + B · seed_{n-2}
      - Tied LM head

    Stored params (cross mode, K=32, d_model=128, n_blocks=N):
      - 8 base seeds (qkv, out, w1, w2 for blocks 0 and 1):
          8 * K² * 4 = 8 * 1024 * 4 = 32,768 floats
      - 8 recurrence matrices (A, B for each of qkv, out, w1, w2):
          8 * K² = 8,192 floats
      - LayerNorm + embedding + biases: ~10k floats
      - TOTAL: ~50k regardless of N

    Vs FibGenLM at the same N=4 / K=32 cross: ~25k seed params per block × 4 = 100k.
    Vs FibGenLM at N=12: ~300k. FibRecLM stays ~50k.
    """

    def __init__(self, vocab_size: int, d_model: int, n_blocks: int,
                 seq_len: int, K: int = 32, mode: str = "cross"):
        super().__init__()
        assert n_blocks >= 2, "need at least 2 base layers"
        assert mode == "cross"
        self.seq_len = seq_len
        self.d_model = d_model
        self.K = K
        self.mode = mode
        self.n_blocks = n_blocks

        self.embed = nn.Embedding(vocab_size, d_model)
        pe = self._crt_pe(seq_len, d_model)
        self.register_buffer("pe", pe)
        mask = torch.tril(torch.ones(seq_len, seq_len))
        self.register_buffer("mask", mask)

        # Basis tables for each of the four FibGen layer shapes:
        #   qkv:  d -> 3d        out: d -> d        w1: d -> 4d        w2: 4d -> d
        for name, in_dim, out_dim in [
            ("qkv", d_model, 3 * d_model),
            ("out", d_model, d_model),
            ("w1", d_model, 4 * d_model),
            ("w2", 4 * d_model, d_model),
        ]:
            basis = make_fib_basis(in_dim, out_dim, K)
            self.register_buffer(f"{name}_cos_i", basis["cos_i"])
            self.register_buffer(f"{name}_sin_i", basis["sin_i"])
            self.register_buffer(f"{name}_cos_j", basis["cos_j"])
            self.register_buffer(f"{name}_sin_j", basis["sin_j"])

        # Base seeds (cross mode: [K², 4]). 4 seeds × 2 base blocks = 8.
        n_components = K * K
        init = 0.1 / math.sqrt(n_components)
        for name in ("qkv", "out", "w1", "w2"):
            for n in (0, 1):
                setattr(self, f"{name}_seed_{n}",
                        nn.Parameter(torch.randn(n_components, 4) * init))

        # Recurrence matrices A, B per layer (K×K each). 8 small matrices.
        for name in ("qkv", "out", "w1", "w2"):
            # Initialize A near identity, B near zero — so deep layers
            # initially produce ~copies of seed_{n-1} (stable start).
            setattr(self, f"A_{name}", nn.Parameter(
                torch.eye(K) + 0.01 * torch.randn(K, K)))
            setattr(self, f"B_{name}", nn.Parameter(0.01 * torch.randn(K, K)))

        # Per-block LayerNorms (these are still per-block — too small
        # to be worth recurring; ~256 floats each).
        self.ln1s = nn.ModuleList(
            [nn.LayerNorm(d_model) for _ in range(n_blocks)]
        )
        self.ln2s = nn.ModuleList(
            [nn.LayerNorm(d_model) for _ in range(n_blocks)]
        )

        self.ln_f = nn.LayerNorm(d_model)
        self.head = nn.Linear(d_model, vocab_size, bias=False)
        self.head.weight = self.embed.weight

    @staticmethod
    def _crt_pe(seq_len: int, d_model: int) -> torch.Tensor:
        pe = torch.zeros(seq_len, d_model)
        pos = torch.arange(0, seq_len, dtype=torch.float)
        moduli = [5, 8, 13, 21, 34, 55, 89, 144]
        n_pairs = d_model // 2
        for i in range(n_pairs):
            m = moduli[i % len(moduli)]
            angle = 2 * math.pi * (pos % m) / m
            pe[:, 2 * i] = torch.sin(angle)
            pe[:, 2 * i + 1] = torch.cos(angle)
        return pe

    def _rec_step(self, A, B, s_p1, s_p2):
        """One Fibonacci recurrence step on a [K², 4] seed."""
        K = self.K
        sp1 = s_p1.view(K, K, 4)
        sp2 = s_p2.view(K, K, 4)
        s_n = torch.einsum("ik,kjc->ijc", A, sp1) + torch.einsum("ik,kjc->ijc", B, sp2)
        return s_n.reshape(K * K, 4)

    def _rec_step_homeo(self, A, B, s_p1, s_p2, delta_prev):
        """Homeostatic Fibonacci recurrence step.

        Full recurrence:
            seed_n = A · s_{n-1} + B · s_{n-2} + H_strength * H_n

        where:
            H_n        = -phi^{-1} · delta_{n-1} · (s_{n-1} - phi^{-1} · s_{n-2})
            H_strength = phi^{-delta_{n-1} / phi^{-2}}

        This is the golden-ratio immune system of the model. The restoring
        force H_strength * H_n pulls seed_n toward the phi-attractor
        whenever the previous step deviated from it, with OmniWeight-shaped
        strength that is gentle when healthy and retires when critically sick.

        Args:
            A, B:        K×K recurrence matrices (trainable)
            s_p1:        seed_{n-1}  [K²*4]
            s_p2:        seed_{n-2}  [K²*4]
            delta_prev:  delta_{n-1} scalar — golden-ratio deviation of the
                         PREVIOUS step, precomputed for efficiency

        Returns:
            s_n:         seed_n  [K²*4]
            delta_n:     delta_n scalar (for passing to the NEXT step)
        """
        K = self.K
        sp1 = s_p1.view(K, K, 4)
        sp2 = s_p2.view(K, K, 4)
        # Standard recurrence part
        s_n_raw = torch.einsum("ik,kjc->ijc", A, sp1) + torch.einsum("ik,kjc->ijc", B, sp2)
        s_n_raw = s_n_raw.reshape(K * K, 4)
        # Homeostatic additive correction
        H_n = _homeostatic_H(s_p1, s_p2, delta_prev)          # [K²*4]
        H_str = _homeostatic_strength(delta_prev)               # scalar
        s_n = s_n_raw + H_str * H_n
        # Compute delta_n for the next step
        delta_n = _phi_delta(s_n, s_p1)
        return s_n, delta_n

    def _all_seeds(self):
        """Returns a list of (qkv_seed, out_seed, w1_seed, w2_seed) for
        each of the n_blocks layers, with layers 2..N computed via the
        Fibonacci recurrence in a way that preserves gradients."""
        seeds = []
        base = {
            "qkv": (self.qkv_seed_0, self.qkv_seed_1),
            "out": (self.out_seed_0, self.out_seed_1),
            "w1":  (self.w1_seed_0,  self.w1_seed_1),
            "w2":  (self.w2_seed_0,  self.w2_seed_1),
        }
        # Initialize the running pairs.
        running = {k: (s0, s1) for k, (s0, s1) in base.items()}
        for n in range(self.n_blocks):
            if n == 0:
                tup = (base["qkv"][0], base["out"][0], base["w1"][0], base["w2"][0])
            elif n == 1:
                tup = (base["qkv"][1], base["out"][1], base["w1"][1], base["w2"][1])
            else:
                new = {}
                for k in ("qkv", "out", "w1", "w2"):
                    s_p2, s_p1 = running[k]
                    s_n = self._rec_step(getattr(self, f"A_{k}"),
                                          getattr(self, f"B_{k}"),
                                          s_p1, s_p2)
                    new[k] = (s_p1, s_n)
                running = new
                tup = (running["qkv"][1], running["out"][1],
                       running["w1"][1], running["w2"][1])
            seeds.append(tup)
        return seeds

    def _all_seeds_homeo(self):
        """Homeostatic seed generation: same as _all_seeds but uses the
        golden-ratio restoring recurrence at every step n >= 2.

        The homeostatic recurrence propagates a delta scalar forward through
        the sequence:
            delta_1 = phi_delta(seed_1, seed_0)
            (seed_2, delta_2) = rec_step_homeo(A, B, seed_1, seed_0, delta_1)
            (seed_3, delta_3) = rec_step_homeo(A, B, seed_2, seed_1, delta_2)
            ...

        Each step uses the previous step's delta to compute H_strength and
        H_n, then produces the next delta for the chain.

        Returns the same shape as _all_seeds: list of per-block tuples.
        Also returns a dict of per-family final-delta values for monitoring.
        """
        seeds = []
        base = {
            "qkv": (self.qkv_seed_0, self.qkv_seed_1),
            "out": (self.out_seed_0, self.out_seed_1),
            "w1":  (self.w1_seed_0,  self.w1_seed_1),
            "w2":  (self.w2_seed_0,  self.w2_seed_1),
        }
        # Bootstrap delta at layer 1: deviation of seed_1 from phi * seed_0.
        # This is the organism's initial health reading.
        deltas = {k: _phi_delta(s1, s0) for k, (s0, s1) in base.items()}
        running = {k: (s0, s1) for k, (s0, s1) in base.items()}

        for n in range(self.n_blocks):
            if n == 0:
                tup = (base["qkv"][0], base["out"][0], base["w1"][0], base["w2"][0])
            elif n == 1:
                tup = (base["qkv"][1], base["out"][1], base["w1"][1], base["w2"][1])
            else:
                new = {}
                new_deltas = {}
                for k in ("qkv", "out", "w1", "w2"):
                    s_p2, s_p1 = running[k]
                    s_n, d_n = self._rec_step_homeo(
                        getattr(self, f"A_{k}"),
                        getattr(self, f"B_{k}"),
                        s_p1, s_p2,
                        deltas[k],
                    )
                    new[k] = (s_p1, s_n)
                    new_deltas[k] = d_n
                running = new
                deltas = new_deltas
                tup = (running["qkv"][1], running["out"][1],
                       running["w1"][1], running["w2"][1])
            seeds.append(tup)
        return seeds, deltas

    def _all_seeds_lucas_homeo(self):
        """Lucas Mirror: extended homeostatic seed generation.

        Augments the Fibonacci (homeostatic) seeds with the Lucas complement.
        The Lucas sequence satisfies the same recurrence as Fibonacci but with
        different initial conditions, and the identity F_n · L_n = F_{2n} makes
        them multiplicatively conjugate — Lucas fills the gaps Fibonacci misses.

        Lucas initial conditions (derived from existing seeds, zero new params):
            L_0 = 2 * seed_0 - seed_1     (Lucas-like starting point)
            L_1 = seed_0                   (Lucas L_1 = F_1 = 1 relationship)

        Lucas recurrence (same A, B matrices, no homeostatic correction):
            L_n = A · L_{n-1} + B · L_{n-2}

        Extended seed at layer n:
            norm_L_n = L_n / (smooth_norm(L_n) + eps)
            seed_n_ext = seed_n + phi^(-n * PHI_INV) * norm_L_n

        The phi^(-n * PHI_INV) decay schedule:
            n=0: phi^0 = 1.00  (full complement at base)
            n=2: phi^(-1.236) ≈ 0.46
            n=4: phi^(-2.472) ≈ 0.21
            Higher layers: Lucas fades, Fibonacci dominates.

        Returns the same format as _all_seeds_homeo: (seeds_per_layer, deltas).
        Introduces zero new trainable parameters.
        """
        # Get base Fibonacci+homeostatic seeds and final deltas
        seeds_per_layer, final_deltas = self._all_seeds_homeo()

        eps = 1e-8

        # Bootstrap Lucas initial conditions for each seed family
        # L_0 = 2 * seed_0 - seed_1,  L_1 = seed_0
        lucas_running = {
            "qkv": (2 * self.qkv_seed_0 - self.qkv_seed_1, self.qkv_seed_0),
            "out": (2 * self.out_seed_0 - self.out_seed_1, self.out_seed_0),
            "w1":  (2 * self.w1_seed_0  - self.w1_seed_1,  self.w1_seed_0),
            "w2":  (2 * self.w2_seed_0  - self.w2_seed_1,  self.w2_seed_0),
        }
        # lucas_running[k] = (L_{n-1}, L_n) at start of each iteration

        extended_seeds = []
        for n, seed_tup in enumerate(seeds_per_layer):
            # Compute phi^(-n * PHI_INV) decay weight
            decay = math.exp(-n * PHI_INV * _LOG_PHI)  # = phi^(-n * PHI_INV)

            # Current Lucas values for each family at layer n
            # At n=0: L_0; at n=1: L_1; at n>=2: computed via recurrence
            if n == 0:
                L_current = {k: v[0] for k, v in lucas_running.items()}
            elif n == 1:
                L_current = {k: v[1] for k, v in lucas_running.items()}
            else:
                # Propagate Lucas recurrence (plain, no homeostatic correction)
                new_lucas = {}
                for k in ("qkv", "out", "w1", "w2"):
                    L_p2, L_p1 = lucas_running[k]
                    L_n = self._rec_step(
                        getattr(self, f"A_{k}"),
                        getattr(self, f"B_{k}"),
                        L_p1, L_p2,
                    )
                    new_lucas[k] = (L_p1, L_n)
                lucas_running = new_lucas
                L_current = {k: v[1] for k, v in lucas_running.items()}

            # Extend each seed in the 4-tuple with its Lucas complement
            qkv_s, out_s, w1_s, w2_s = seed_tup
            ext_seeds = []
            for seed, k in zip((qkv_s, out_s, w1_s, w2_s), ("qkv", "out", "w1", "w2")):
                L_n = L_current[k]
                norm_L = L_n / (_smooth_norm(L_n) + eps)
                ext_seeds.append(seed + decay * norm_L)

            extended_seeds.append(tuple(ext_seeds))

        return extended_seeds, final_deltas

    def _layer_forward(self, x, mask, n, seeds_n):
        qkv_s, out_s, w1_s, w2_s = seeds_n
        x_norm = self.ln1s[n](x)
        qkv_basis = {
            "cos_i": self.qkv_cos_i, "sin_i": self.qkv_sin_i,
            "cos_j": self.qkv_cos_j, "sin_j": self.qkv_sin_j,
        }
        qkv = stateless_fibgen_forward(x_norm, qkv_s, qkv_basis, self.K)
        q, k, v = qkv.chunk(3, dim=-1)
        scale = 1.0 / math.sqrt(self.d_model)
        scores = (q @ k.transpose(-2, -1)) * scale
        scores = scores.masked_fill(mask == 0, float("-inf"))
        attn = F.softmax(scores, dim=-1)
        attn_out_basis = {
            "cos_i": self.out_cos_i, "sin_i": self.out_sin_i,
            "cos_j": self.out_cos_j, "sin_j": self.out_sin_j,
        }
        x = x + stateless_fibgen_forward(attn @ v, out_s, attn_out_basis, self.K)
        # FFN
        x_norm2 = self.ln2s[n](x)
        w1_basis = {
            "cos_i": self.w1_cos_i, "sin_i": self.w1_sin_i,
            "cos_j": self.w1_cos_j, "sin_j": self.w1_sin_j,
        }
        w2_basis = {
            "cos_i": self.w2_cos_i, "sin_i": self.w2_sin_i,
            "cos_j": self.w2_cos_j, "sin_j": self.w2_sin_j,
        }
        h = stateless_fibgen_forward(x_norm2, w1_s, w1_basis, self.K)
        h = F.gelu(h)
        x = x + stateless_fibgen_forward(h, w2_s, w2_basis, self.K)
        return x

    def forward(self, token_ids):
        B, T = token_ids.shape
        h = self.embed(token_ids) + self.pe[:T]
        m = self.mask[:T, :T]
        seeds_per_layer = self._all_seeds()
        for n, seeds_n in enumerate(seeds_per_layer):
            h = self._layer_forward(h, m, n, seeds_n)
        h = self.ln_f(h)
        return self.head(h)

    def storage_summary(self):
        # ONLY the persistent parameters count (base seeds + recurrence
        # matrices + LayerNorms + embedding/head). The recurrence-derived
        # seeds are ephemeral.
        stored = sum(p.numel() for p in self.parameters())
        # Dense-equivalent: as if every block had full nn.Linear weights
        d = self.d_model
        dense_per_block = (3*d*d + d*d + d*4*d + 4*d*d) + 2*2*d  # +LN
        dense_eq = self.n_blocks * dense_per_block + self.embed.weight.numel()
        return {"stored": stored, "dense_equivalent": dense_eq,
                "compression": dense_eq / max(stored, 1)}


class FibRecLMHomeo(FibRecLM):
    """FibRecLM with golden-ratio homeostatic recurrence.

    Extends FibRecLM by replacing the plain Fibonacci recurrence with the
    homeostatic version at layers n >= 2. The homeostatic recurrence adds a
    phi-attractor restoring force to the seed generation, derived entirely
    from the golden ratio and the existing seed parameters — zero new
    trainable parameters.

    BIOLOGICAL ANALOGY:
        FibRecLM seeds are like a living organism whose metabolism is supposed
        to maintain a Fibonacci identity (each generation ~ phi times the
        previous). But A and B can drift the organism to any ratio. Without
        homeostasis, the organism has no immune system — perturbations accumulate.

        FibRecLMHomeo adds the immune system. The restoring force H_n is the
        organism's attempt to return to equilibrium. The OmniWeight-shaped
        H_strength is the immune RESPONSE CURVE:
          - Healthy organism (delta small): gentle maintenance, full strength
          - Stressed organism (delta moderate): moderate corrective force
          - Critically ill (delta large): homeostasis RETREATS, lets gradient
            descent on A,B handle recovery (prevents cytokine storm)

    STRUCTURAL IMPLICATION FOR W_layer:
        Without homeostasis:
            seed_n is an arbitrary K²×4 matrix. W_n has no constrained
            relationship to W_{n-1}. Each layer weight matrix lives
            independently in K²-dimensional weight space.

        With homeostasis converged (delta -> 0):
            seed_n -> phi * seed_{n-1}
            => W_n -> phi * W_{n-1}
            => W_n and W_{n-1} are PROPORTIONAL: same singular vectors,
               singular values scaled by phi.

        Consequence: the layer weight matrices form a GEOMETRIC SEQUENCE
        in matrix space with ratio phi. They all share the same left and
        right singular subspaces — the same "directions" in feature space
        — with only their MAGNITUDES varying as phi^{n-1} * ||W_1||.

        In other words: the model is constrained to a 1D ray in weight
        space (the Fibonacci manifold), not a K²-dimensional free space.
        This is the Fibonacci identity of the organism: all layers express
        the same underlying structure at different scales.

    FIXED POINT ANALYSIS:
        At fixed point delta_n = 0 for all n (perfect health):
            H_n = 0  (no correction needed)
            H_strength = phi^0 = 1 (but H_n = 0 anyway)
            seed_n = A * s_{n-1} + B * s_{n-2}

        For this to be consistent with s_n = phi * s_{n-1}:
            phi * s_{n-1} = A * s_{n-1} + B * s_{n-2}
            phi * phi * s_{n-2} = A * phi * s_{n-2} + B * s_{n-2}
            => (A * phi + B) = phi^2 * I  (Cayley-Hamilton constraint)

        This is NOT imposed as a constraint — the homeostasis ATTRACTS toward
        it. If A,B satisfy this constraint, then s_n = phi * s_{n-1} is a
        fixed point of the FULL homeostatic recurrence.

    DIFFERENTIABILITY:
        All components are smooth in the parameters:
          - delta_n uses smooth_norm = sqrt(v·v + eps²) — no cusp at v=0
          - H_n is linear in s_p1, s_p2, bilinear in delta (smooth)
          - H_strength = exp(-delta * const) — smooth exponential everywhere
          - The full recurrence is a smooth function of (seed_0, seed_1, A, B)

    MONITORING:
        The forward method returns (logits, deltas_dict) when return_deltas=True.
        deltas_dict maps each seed family ("qkv","out","w1","w2") to the delta
        scalar at the FINAL recurrence step. These can be logged to track
        organism health during training.
    """

    def forward(self, token_ids, return_deltas: bool = False):
        B, T = token_ids.shape
        h = self.embed(token_ids) + self.pe[:T]
        m = self.mask[:T, :T]
        seeds_per_layer, final_deltas = self._all_seeds_lucas_homeo()
        for n, seeds_n in enumerate(seeds_per_layer):
            h = self._layer_forward(h, m, n, seeds_n)
        h = self.ln_f(h)
        logits = self.head(h)
        if return_deltas:
            return logits, final_deltas
        return logits

    def health_report(self, token_ids) -> dict:
        """Run a forward pass and return per-family delta values.

        delta values near 0 => healthy (organism near phi-attractor).
        delta values > phi^{-2} ≈ 0.38 => stressed.
        delta values >> 1 => homeostasis has retreated, gradient in control.

        Returns:
            dict with keys: 'qkv', 'out', 'w1', 'w2' mapping to float deltas,
            plus 'mean_delta' for a summary scalar.
        """
        with torch.no_grad():
            _, deltas = self.forward(token_ids, return_deltas=True)
        report = {k: v.item() for k, v in deltas.items()}
        report["mean_delta"] = sum(report.values()) / len(report)
        report["phi_inv2_threshold"] = PHI_INV2   # crossover scale for reference
        return report
