"""Recursive substrate models — depth via Fibonacci recurrence on seeds.

Idea 1 from the recursive-self-improvement menu:
  - Layer 0 and 1 have LEARNED FibGen seeds (the "base case")
  - Layer n >= 2: seed_n = A · seed_{n-1} + B · seed_{n-2}
  - A, B are small K×K matrices, also learned

Storage cost: 2 base seeds + 2 recurrence matrices = O(K²) regardless
of depth. Layers 2..N are generated by the substrate recurrence.

Gradient flows correctly because we use a STATELESS FibGen-style
forward that takes the seed as an argument instead of holding it as
a parameter.

Homeostatic recurrence (FibRecLMHomeo):
  Adds a phi-attractor restoring force to the seed recurrence — the
  model's "immune system" that maintains Fibonacci identity under
  perturbation. Derived entirely from phi and the existing seeds;
  introduces zero new trainable parameters.

  Full recurrence:
    delta_n   = smooth_norm(s_n - phi * s_{n-1}) / (smooth_norm(s_{n-1}) + eps)
    H_n       = -phi^{-1} * delta_{n-1} * (s_{n-1} - phi^{-1} * s_{n-2})
    H_strength = phi^{-delta_{n-1} / phi^{-2}}
    seed_n    = A · s_{n-1} + B · s_{n-2} + H_strength * H_n

  See HOMEOSTATIC_DERIVATION.md for the full derivation.
"""

